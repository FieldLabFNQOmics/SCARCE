#' cluster_variants.R
#'
#' This function performs cell clustering based on variant genotypes.
#'
#' Two modes are supported:
#'   "panel" - high cell-number amplicon panel data (e.g. Tapestri). Variance-based
#'             feature selection, cosine distance on AF, UMAP + DBSCAN.
#'   "wgs"   - low cell-number whole-genome data (e.g. ResolveOME scWGS). Binary alt/ref
#'             calls with AF and depth thresholds, co-occurrence filtering against a
#'             shuffled null, double-centred cosine distance, hierarchical clustering.
#'
#' @param seurat_obj Optional input seurat object created using prepare_annotation_data()
#' @param genotypes_file Path to *genotypes.tsv file generated by find_somatic_variants()
#' @param summary_file Path to *summary.tsv file generated by find_somatic_variants()
#' @param plot_directory Optional path to a directory where plots will be saved
#' @param n_features Panel mode. Target number of variants to use for clustering (Default = 100)
#' @param sample_ID Sample identifier to be added to seurat object
#' @param n_neighbors Passed to uwot::umap, capped at n_cells - 1 (Default = 30)
#' @param min_dist Passed to uwot::umap (Default = 0.3)
#' @param dist_metric Passed to uwot::umap (Default = "euclidean")
#' @param dbscan_eps Eps metric passed to dbscan::dbscan (Default = 0.8)
#' @param min_data_portion Panel mode. Minimum data availability for filtering variants (Default = 0.8)
#' @param rare_frequency_max Panel mode. Max frequency threshold for selecting rare variants (Default = 0.02)
#' @param min_overlap Minimum number of jointly observed variants between two cells
#'                    for calculating a distance (Default = 10)
#' @param min_alt_count Minimum number of cells carrying a mutation for it to be included
#'                      (Default = NULL; 5 in panel mode, 3 in WGS mode)
#' @param prune_correlated_variants Panel mode. Filter out selected variants highly correlated
#'                                  with each other (Experimental) (Default = FALSE)
#' @param rare_var_weighting Panel mode. Proportion of clustering features that should be rare variants (Default = 0.1)
#' @param minPts minPts metric passed to dbscan::dbscan (Default = NULL, scaled to cell number)
#' @param clustering_seed Seed for candidate sampling, the co-occurrence null and UMAP (Default = NULL)
#' @param data_type One of "auto", "panel" or "wgs". "auto" uses "wgs" when the cell number
#'                  is below small_n_threshold (Default = "auto")
#' @param cluster_method One of "auto", "dbscan" or "hclust". "auto" uses "hclust" when the
#'                       cell number is below small_n_threshold (Default = "auto")
#' @param small_n_threshold Cell number below which "auto" settings switch to WGS/hclust (Default = 200)
#' @param exclude_cells Optional vector of cell barcodes to drop before clustering (Default = NULL)
#' @param min_alt_reads WGS mode. Minimum alt reads (AF * DP) to call a cell alt (Default = 2)
#' @param min_alt_af WGS mode. Minimum AF to call a cell alt. Cells with AF > 0 that fail
#'                   min_alt_reads or min_alt_af are set to NA rather than reference (Default = 0.3)
#' @param min_dp_ref WGS mode. Minimum depth to call a cell confidently reference (Default = 5)
#' @param min_ref_count WGS mode. Minimum number of cells confidently reference (Default = 2)
#' @param max_p_alt WGS mode. Maximum fraction of covered cells carrying alt, removes likely
#'                  germline variants (Default = 0.6)
#' @param max_candidates WGS mode. Maximum candidate variants read from the genotypes file;
#'                       larger pools are randomly sampled (Default = 100000)
#' @param jaccard_thresh WGS mode. Carrier-set Jaccard similarity needed for two variants to
#'                       count as co-occurring partners (Default = 0.6)
#' @param min_partners WGS mode. Minimum co-occurring partners to keep a variant, applied as a
#'                     floor on the null-calibrated threshold (Default = 2)
#' @param cooccurrence_quantile WGS mode. Quantile of shuffled-null partner counts a variant
#'                              must exceed (Default = 0.99)
#' @param max_k hclust mode. Maximum number of clusters tested by silhouette (Default = 8)
#' @param min_cluster_size hclust mode. Values of k producing a cluster smaller than this
#'                         are skipped (Default = 3)
#' @param n_clusters hclust mode. Fix the number of clusters instead of choosing by silhouette (Default = NULL)
#' @param n_boot hclust mode. Number of bootstrap replicates (resampling variants) used to
#'   estimate support for each branch of the dendrogram. 0 disables it (Default = 0)
#' @param summary_af_prefilter WGS mode. Before sampling candidates, drop variants whose
#'                             median_AF_mutants in the summary file is below min_alt_af (Default = TRUE)
#' @return Seurat object. In hclust mode, @misc holds variant_hclust and variant_silhouette,
#'         and cells without informative calls are left unassigned (cluster 0);
#'         @misc also holds variant_dist (up to 2000 cells) and, in WGS mode, variant_binary
#'         and variant_uninformative.
#' @export

cluster_variants <- function(
    seurat_obj = NULL,
    genotypes_file,
    summary_file,
    plot_directory = NULL,
    n_features = 100,
    sample_ID = NULL,
    n_neighbors = 30,
    min_dist = 0.3,
    dist_metric = "euclidean",
    dbscan_eps = 0.8,
    min_data_portion = 0.8,
    rare_frequency_max = 0.02,
    min_overlap = 10L,
    min_alt_count = NULL,
    prune_correlated_variants = FALSE,
    rare_var_weighting = 0.1,
    minPts = NULL,
    clustering_seed = NULL,
    data_type = c("auto", "panel", "wgs"),
    cluster_method = c("auto", "dbscan", "hclust"),
    small_n_threshold = 200,
    exclude_cells = NULL,
    min_alt_reads = 2,
    min_alt_af = 0.3,
    min_dp_ref = 5,
    min_ref_count = 2,
    max_p_alt = 0.6,
    max_candidates = 100000,
    jaccard_thresh = 0.6,
    min_partners = 2,
    cooccurrence_quantile = 0.99,
    max_k = 8,
    min_cluster_size = 3,
    n_clusters = NULL,
    n_boot = 0,
    summary_af_prefilter = TRUE
){

  data_type <- match.arg(data_type)
  cluster_method <- match.arg(cluster_method)

  if(!is.null(seurat_obj)){
    barcodes <- colnames(seurat_obj)
    sample_ID <- seurat_obj@meta.data$sample_ID[1]
  }else{
    barcodes <- .detect_barcodes(genotypes_file)
    if(is.null(sample_ID)){
      stop("Please provide sample_ID")
    }
  }

  if (!is.null(exclude_cells)) {
    missing_cells <- setdiff(exclude_cells, barcodes)
    if (length(missing_cells) > 0) warning("exclude_cells not found: ", paste(missing_cells, collapse = ", "))
    n_before <- length(barcodes)
    barcodes <- setdiff(barcodes, exclude_cells)
    message("Excluded ", n_before - length(barcodes), " cells")
  }

  n_cells <- length(barcodes)
  small_n <- n_cells < small_n_threshold
  if (data_type == "auto")      data_type      <- if (small_n) "wgs" else "panel"
  if (cluster_method == "auto") cluster_method <- if (small_n) "hclust" else "dbscan"
  if (is.null(min_alt_count))   min_alt_count  <- if (data_type == "wgs") 3 else 5
  message("Cells: ", n_cells, " | data_type: ", data_type, " | cluster_method: ", cluster_method)

  ###############
  # File access #
  ###############

  fmt_line <- readLines(genotypes_file, n = 1L)
  format_fields <- strsplit(gsub("^#FORMAT=", "", fmt_line), ";", fixed = TRUE)[[1]]
  cols <- colnames(data.table::fread(genotypes_file, nrows = 20L, sep = "\t"))

  # Read selected rows (summary row numbers) from the genotypes file
  read_rows <- function(row_numbers) {
    row_idx <- sort(unique(row_numbers)) + 2L  # add two for #FORMAT description and colnames
    idx_file <- tempfile()
    on.exit(unlink(idx_file), add = TRUE)
    writeLines(as.character(row_idx), idx_file)
    out <- tryCatch({
      data.table::fread(
        cmd = sprintf("awk 'NR==FNR{keep[$1]; next} FNR in keep' %s %s",
                      shQuote(idx_file), shQuote(genotypes_file)),
        sep = "\t", header = FALSE, col.names = cols)
    }, error = function(e) {
      message("Warning: Genotype file read failed: ", conditionMessage(e), " - using fallback.")
      rbindlist(lapply(row_idx, function(r) {
        fread(genotypes_file, skip = r - 1L, nrows = 1L, header = FALSE, sep = "\t")
      }), use.names = FALSE) %>%
        setNames(cols)
    })
    out <- as.data.frame(out)
    rownames(out) <- make.unique(as.character(out$plot_ID))
    out
  }

  # Extract one FORMAT field as a numeric variant x cell matrix
  get_field <- function(variants, field) {
    i <- match(field, format_fields)
    if (is.na(i)) stop("FORMAT field '", field, "' not found. Available: ",
                       paste(format_fields, collapse = ", "))
    m <- sapply(variants[barcodes], function(s)
      suppressWarnings(as.numeric(vapply(strsplit(s, ";", fixed = TRUE), `[`, "", i))))
    matrix(m, nrow = nrow(variants), dimnames = list(rownames(variants), barcodes))
  }

  uninf <- character(0)   # cells without informative calls (set in WGS mode)

  summary_dt <- fread(summary_file) %>%
    mutate(
      rownumber = row_number(),
      p_alt = ifelse(data_cnt_total > 0, alt_cnt_total / data_cnt_total, NA_real_),
      evidence_score =
        log1p(alt_cnt_total) *
        log1p(mean_DP_total) *
        (mean_GQ_total / 30)
    )

  if (data_type == "panel") {

    ##########################
    # Panel: Find Features   #
    ##########################

    all_variants <- summary_dt %>%
      filter(filter == ".", data_proportion_total >= min_data_portion) %>%
      # NGT variance (max = 0.5, deprioritises too low OR too high frequency)
      mutate(var_ngt = p_alt * (1 - p_alt)) %>%
      arrange(desc(var_ngt))

    if (n_cells * rare_frequency_max < min_alt_count) {
      message("Skipping rare variant selection: n_cells * rare_frequency_max < min_alt_count")
      rare_variants <- all_variants[0, ]
      n_common <- n_features
    } else {
      rare_variants <- all_variants %>%
        filter(
          p_alt < rare_frequency_max,
          mean_GQ_total >= 30,
          alt_cnt_total >= min_alt_count
        ) %>%
        arrange(desc(evidence_score)) %>%
        head(n_features * rare_var_weighting)
      n_common <- n_features * (1 - rare_var_weighting)
    }
    rare_vars_vector <- rare_variants$plot_ID

    selection <- bind_rows(
      all_variants %>% head(n_common), rare_variants
    ) %>%
      pull(rownumber)

    message("Using ", length(unique(selection)), " features including ", nrow(rare_variants), " rare variants")

    variants <- read_rows(selection)
    af_matrix <- get_field(variants, "AF")

    if(prune_correlated_variants){
      var_corr <- cor(t(af_matrix), method = "spearman", use = "pairwise.complete.obs")
      corr_thresh <- 0.8
      adj <- var_corr > corr_thresh
      diag(adj) <- FALSE
      g <- graph_from_adjacency_matrix(adj, mode = "undirected")
      components <- components(g)$membership

      variant_scores <- all_variants %>% column_to_rownames("plot_ID") %>%
        dplyr::select(var_ngt, p_alt, alt_cnt_total, mean_GQ_total)
      variant_scores <- variant_scores[rownames(var_corr),]
      variant_scores <- variant_scores %>%
        rownames_to_column("variant") %>%
        mutate(
          score =
            var_ngt *                      # prefers non-fixed variants
            log1p(alt_cnt_total) *         # enough support
            (mean_GQ_total / 30)           # quality weighting
        )
      variant_scores$component <- components

      selected <- variant_scores %>%
        group_by(component) %>%
        slice_max(score, n = 1) %>%
        pull(variant)

      selected <- unique(c(selected, rare_vars_vector))   # re-add rare variants
      message(length(selected), " variants remaining after pruning")
      af_matrix <- af_matrix[selected, , drop = FALSE]
    }

    min_cells_with_signal <- 5L
    nonzero_counts <- rowSums(af_matrix > 0, na.rm = TRUE)
    row_var        <- matrixStats::rowVars(af_matrix, na.rm = TRUE)
    keep <- (nonzero_counts >= min_cells_with_signal) & (row_var > 0)
    af_matrix <- af_matrix[keep, , drop = FALSE]
    if (nrow(af_matrix) == 0) stop("No variants passed filtering")

    D <- .cosine_dist_na_fast(af_matrix, min_overlap = min_overlap)

    boot_X <- af_matrix
    boot_dist <- function(X) .cosine_dist_na_fast(X, min_overlap = min_overlap)

  } else {

    ##########################
    # WGS: Find Features     #
    ##########################

    if (prune_correlated_variants) {
      message("prune_correlated_variants is ignored in WGS mode (co-occurrence filtering is used instead)")
    }

    cand <- summary_dt %>%
      filter(filter == ".",
             alt_cnt_total >= min_alt_count,
             data_cnt_total - alt_cnt_total >= min_ref_count,
             p_alt <= max_p_alt)
    # Remove variants whose mutant calls are mostly low-AF before sampling, so the
    # sampled pool is enriched for real variants
    if (summary_af_prefilter && "median_AF_mutants" %in% names(cand)) {
      cand <- cand %>% filter(median_AF_mutants >= min_alt_af)
    }
    message(nrow(cand), " variants pass the summary pre-filter")
    if (nrow(cand) == 0) stop("No candidate variants passed the summary pre-filter")

    # Random sampling avoids biasing the pool towards common, high-depth variants
    if (nrow(cand) > max_candidates) {
      if (!is.null(clustering_seed)) set.seed(clustering_seed)
      cand <- cand %>% slice_sample(n = max_candidates)
      message("Randomly sampled ", max_candidates, " candidate variants")
    }

    variants <- read_rows(cand$rownumber)
    AF <- get_field(variants, "AF")
    DP <- get_field(variants, "DP")

    # 1 = alt (enough alt reads and AF), 0 = confidently reference, NA = uncertain
    alt_reads <- round(AF * DP)
    B <- ifelse(is.finite(alt_reads) & alt_reads >= min_alt_reads & AF >= min_alt_af, 1,
                ifelse(is.finite(AF) & AF > 0, NA,
                       ifelse(is.finite(DP) & DP >= min_dp_ref, 0, NA)))

    keep <- rowSums(B == 1, na.rm = TRUE) >= min_alt_count &
            rowSums(B == 0, na.rm = TRUE) >= min_ref_count &
            rowMeans(B, na.rm = TRUE) <= max_p_alt
    B <- B[keep, , drop = FALSE]
    message(nrow(B), " variants after alt/reference calling filters")
    if (nrow(B) == 0) stop("No variants passed alt/reference calling filters - try lowering min_dp_ref or min_alt_af")

    # Flag cells with outlying alt rates (possible doublets, contamination or low-quality cells)
    cell_alt_rate <- colMeans(B, na.rm = TRUE)
    z <- (cell_alt_rate - median(cell_alt_rate, na.rm = TRUE)) / mad(cell_alt_rate, na.rm = TRUE)
    outliers <- names(z)[is.finite(z) & abs(z) > 3]
    if (length(outliers) > 0) {
      message("Cells with outlying alt rate (|robust z| > 3), consider exclude_cells: ",
              paste0(outliers, " (", round(cell_alt_rate[outliers], 3), ")", collapse = ", "))
    }

    # Co-occurrence filter: keep variants whose carrier sets overlap with more other
    # variants than expected under a null that preserves each variant's carrier count
    # and missingness, and each cell's alt rate
    carr <- (B == 1) & !is.na(B)
    storage.mode(carr) <- "numeric"
    partners <- .count_partners(carr, jaccard_thresh)

    if (!is.null(clustering_seed)) set.seed(clustering_seed)
    Bn <- .shuffle_rows_weighted(B)
    carr_n <- (Bn == 1) & !is.na(Bn)
    storage.mode(carr_n) <- "numeric"
    null_partners <- .count_partners(carr_n, jaccard_thresh)

    # Threshold per carrier count, since low-carrier variants gain chance partners easily
    k <- rowSums(carr)
    thr_by_k <- tapply(null_partners, k, quantile, probs = cooccurrence_quantile, names = FALSE)
    row_thr <- pmax(min_partners, as.numeric(thr_by_k[as.character(k)]) + 1)
    keep_co <- partners >= row_thr
    message("Co-occurrence: ", sum(keep_co), " variants exceed the shuffled null (",
            round(mean(null_partners >= row_thr) * 100, 2), "% of null variants would pass)")
    rm(Bn, carr, carr_n)

    B <- B[keep_co, , drop = FALSE]
    if (nrow(B) < min_overlap) stop("Too few variants left after co-occurrence filtering - try increasing max_candidates")

    # Double-centred cosine distance: remove each variant's frequency and each cell's
    # detection rate so distances reflect shared carrier patterns, not cell quality
    D <- .wgs_dist(B, min_overlap)

    boot_X <- B
    boot_dist <- function(X) .wgs_dist(X, min_overlap)

    # Cells with only one call value carry no clone information; centring would give
    # them spurious near-identical profiles, so set them to maximum distance
    uninf <- colnames(B)[apply(B, 2, function(x) length(unique(x[!is.na(x)])) < 2)]
    if (length(uninf) > 0) {
      warning(length(uninf), " of ", ncol(B), " cells have no informative calls among the ",
              nrow(B), " selected variants and will be left unassigned (cluster 0). ",
              "If this is a large fraction, try increasing max_candidates. ",
              "Cell IDs are in @misc$variant_uninformative.")
    }

    af_matrix <- AF[rownames(B), , drop = FALSE]
  }

  #################
  # Seurat Object #
  #################

  assay_counts <- af_matrix
  assay_counts[!is.finite(assay_counts)] <- 0
  assay_counts <- as(Matrix::Matrix(assay_counts, sparse = TRUE), "dgCMatrix")

  if (is.null(seurat_obj)) {
    seurat_obj <- Seurat::CreateSeuratObject(counts = assay_counts, assay = "variants")
  } else {
    seurat_obj[["variants"]] <- Seurat::CreateAssayObject(counts = assay_counts)
  }
  seurat_obj <- Seurat::SetAssayData(
    seurat_obj, assay = "variants", layer = "data", new.data = assay_counts
  )
  Seurat::DefaultAssay(seurat_obj) <- "variants"

  ########
  # UMAP #
  ########
  # Used for clustering in dbscan mode, visualisation only in hclust mode

  if(!is.null(clustering_seed)){
    set.seed(clustering_seed)
  }

  n_nb <- min(n_neighbors, n_cells - 1L)
  if (n_nb < n_neighbors) message("n_neighbors capped at ", n_nb, " (n_cells - 1)")

  umap_emb <- uwot::umap(
    D,
    n_neighbors = n_nb, min_dist = min_dist, metric = dist_metric,
    n_components = 2, verbose = FALSE
  )
  rownames(umap_emb) <- colnames(af_matrix)
  colnames(umap_emb) <- c("UMAP_1", "UMAP_2")

  ##############
  # Clustering #
  ##############

  if (cluster_method == "dbscan") {
    if (n_boot > 0) message("n_boot is only used with cluster_method = 'hclust'")

    if(is.null(minPts)){
      minPts <- max(20L, round(n_cells * 0.01))
    }
    if (minPts >= n_cells) {
      minPts <- max(2L, floor(n_cells / 4))
      message("minPts exceeded cell number - reduced to ", minPts,
              ". Consider cluster_method = 'hclust' for small cell numbers.")
    }
    db <- dbscan::dbscan(umap_emb, eps = dbscan_eps, minPts = minPts)
    clusters <- setNames(db$cluster, rownames(umap_emb))   # 0 = noise

  } else {

    # Cluster informative cells only; uninformative cells stay unassigned (cluster 0)
    inf_cells <- setdiff(attr(D, "Labels"), uninf)
    if (length(inf_cells) < 4) stop("Fewer than 4 informative cells - try increasing max_candidates")
    Dh <- stats::as.dist(as.matrix(D)[inf_cells, inf_cells])

    hc <- hclust(Dh, method = "ward.D2")

    boot_support <- NULL
    if (n_boot > 0) {
      message("Bootstrapping dendrogram (", n_boot, " replicates)...")
      if (!is.null(clustering_seed)) set.seed(clustering_seed)
      boot_support <- .bootstrap_clades(hc, boot_X[, inf_cells, drop = FALSE], boot_dist, n_boot)
      seurat_obj@misc$variant_bootstrap <- boot_support
    }


    ks <- 2:min(max_k, length(inf_cells) - 1L)
    sil <- sapply(ks, function(k) {
      cl <- cutree(hc, k)
      if (min(table(cl)) < min_cluster_size) return(NA_real_)
      mean(cluster::silhouette(cl, Dh)[, 3])
    })
    if (all(is.na(sil))) {
      warning("No k gives clusters of at least min_cluster_size cells (likely outlier cells) - ",
              "ignoring min_cluster_size. Check rowMeans of @misc$variant_dist for outliers.")
      sil <- sapply(ks, function(k) mean(cluster::silhouette(cutree(hc, k), Dh)[, 3]))
    }
    best_k <- if (!is.null(n_clusters)) n_clusters else ks[which.max(sil)]
    clusters <- setNames(rep(0L, attr(D, "Size")), attr(D, "Labels"))
    clusters[inf_cells] <- cutree(hc, best_k)
    message("Best k = ", best_k, " (mean silhouette ", round(max(sil, na.rm = TRUE), 3), ")")

    plot(hc, main = paste0(sample_ID, " variant clustering"), xlab = "", sub = "")
    rect.hclust(hc, k = best_k)
    if (!is.null(plot_directory)) {
      png(file.path(plot_directory, paste0(sample_ID, "_variant_dendrogram.png")),
          width = 25, height = 15, units = "cm", res = 300)
      draw_dend <- function() {
        plot(hc, main = paste0(sample_ID, " variant clustering"), xlab = "", sub = "")
        rect.hclust(hc, k = best_k)
        if (!is.null(boot_support)) {
          text(.node_x(hc), hc$height, labels = boot_support$support,
              pos = 3, offset = 0.2, cex = 0.6, col = "#C0392B")
        }
      }
      draw_dend()
      if (!is.null(plot_directory)) {
        png(file.path(plot_directory, paste0(sample_ID, "_variant_dendrogram.png")),
            width = 25, height = 15, units = "cm", res = 300)
        draw_dend()
        dev.off()
      }
    }
    seurat_obj@misc$variant_hclust <- hc
    seurat_obj@misc$variant_silhouette <- setNames(sil, ks)
  }

  common <- intersect(colnames(seurat_obj), names(clusters))
  seurat_obj <- subset(seurat_obj, cells = common)
  umap_emb   <- umap_emb[common, , drop = FALSE]

  ######################
  # Add UMAP To Seurat #
  ######################
  seurat_obj[["umap.variants"]] <- Seurat::CreateDimReducObject(
    embeddings = umap_emb,
    key = "umapVAF_",
    assay = "variants"
  )
  seurat_obj$variants_clusters <- clusters[colnames(seurat_obj)]
  Seurat::Idents(seurat_obj) <- "variants_clusters"

  # Keep intermediates for diagnostics
  if (n_cells <= 2000) seurat_obj@misc$variant_dist <- D
  if (data_type == "wgs") {
    seurat_obj@misc$variant_binary <- B
    seurat_obj@misc$variant_uninformative <- uninf
  }

  p <- Seurat::DimPlot(
    seurat_obj, reduction = "umap.variants",
    group.by = "variants_clusters",
    label = TRUE, repel = TRUE, label.box = TRUE, pt.size = 2
  )
  print(p)

  if (!is.null(plot_directory)) {
    ggplot2::ggsave(plot = p, filename = file.path(plot_directory, paste0(sample_ID, "_variant_umap.png")),
                    width = 25, height = 25, units = "cm", dpi = 300)
  }

  invisible(seurat_obj)
}


# Cosine distance between cells, ignoring NA values
.cosine_dist_na_fast <- function(A, min_overlap = 10L) {
  W  <- is.finite(A)
  A0 <- A
  A0[!W] <- 0
  storage.mode(W) <- "numeric"

  NUM  <- crossprod(A0)              # sum of products over jointly observed
  OVER <- crossprod(W)               # jointly observed counts
  S    <- crossprod(A0 * A0, W)      # squared norm of a over b's observed support
  DEN  <- sqrt(S * t(S))

  COS <- ifelse(DEN > 0, NUM / DEN, 0)
  D <- 1 - COS
  D[OVER < min_overlap] <- 1
  diag(D) <- 0
  D <- (D + t(D)) * 0.5
  stats::as.dist(D)
}


# Number of other variants whose carrier set has Jaccard >= thresh with each variant.
# Computed in blocks to limit memory with many variants.
.count_partners <- function(carr, jaccard_thresh, block = NULL) {
  # Default block keeps each intermediate matrix around 20M entries (~160 MB)
  if (is.null(block)) block <- max(100L, floor(2e7 / nrow(carr)))
  n_carr <- rowSums(carr)
  out <- integer(nrow(carr))
  for (s in seq(1L, nrow(carr), by = block)) {
    idx <- s:min(s + block - 1L, nrow(carr))
    inter <- tcrossprod(carr[idx, , drop = FALSE], carr)
    jac <- inter / (outer(n_carr[idx], n_carr, "+") - inter)
    jac[cbind(seq_along(idx), idx)] <- 0
    out[idx] <- rowSums(jac >= jaccard_thresh, na.rm = TRUE)
  }
  out
}


# Null for co-occurrence: for each variant, keep its carrier count and covered cells,
# but place carriers among covered cells with probability proportional to each cell's
# overall alt rate, so high-detection cells are expected to share more variants
.shuffle_rows_weighted <- function(B) {
  out <- B
  w <- colMeans(B, na.rm = TRUE)
  w[!is.finite(w)] <- 0
  w <- w + 1e-6
  for (i in seq_len(nrow(B))) {
    ok <- which(!is.na(B[i, ]))
    k <- sum(B[i, ok] == 1)
    out[i, ok] <- 0
    if (k > 0) out[i, ok[sample.int(length(ok), k, prob = w[ok])]] <- 1
  }
  out
}

# Double-centred cosine distance for WGS binary calls. Cells with only one call
# value carry no clone information and are set to maximum distance
.wgs_dist <- function(B, min_overlap) {
  Bc <- B - rowMeans(B, na.rm = TRUE)
  Bc <- sweep(Bc, 2, colMeans(Bc, na.rm = TRUE))
  D <- as.matrix(.cosine_dist_na_fast(Bc, min_overlap = min_overlap))
  uninf <- apply(B, 2, function(x) length(unique(x[!is.na(x)])) < 2)
  if (any(uninf)) {
    D[uninf, ] <- max(D)
    D[, uninf] <- max(D)
    diag(D) <- 0
  }
  stats::as.dist(D)
}

# Cell sets under each merge of an hclust tree, as sorted strings
.clades <- function(hc) {
  n <- nrow(hc$merge)
  members <- vector("list", n)
  for (i in seq_len(n)) {
    m <- hc$merge[i, ]
    members[[i]] <- sort(c(
      if (m[1] < 0) hc$labels[-m[1]] else members[[m[1]]],
      if (m[2] < 0) hc$labels[-m[2]] else members[[m[2]]]
    ))
  }
  vapply(members, paste, character(1), collapse = "|")
}

# Bootstrap support: resample variants (rows) with replacement, rebuild the tree,
# and record how often each original clade reappears exactly
.bootstrap_clades <- function(hc, X, dist_fun, n_boot, method = "ward.D2") {
  ref <- .clades(hc)
  hits <- numeric(length(ref))
  for (b in seq_len(n_boot)) {
    Xb <- X[sample.int(nrow(X), replace = TRUE), , drop = FALSE]
    hb <- hclust(dist_fun(Xb), method = method)
    hits <- hits + (ref %in% .clades(hb))
  }
  data.frame(merge = seq_along(ref),
             height = hc$height,
             n_cells = lengths(strsplit(ref, "|", fixed = TRUE)),
             support = round(100 * hits / n_boot),
             clade = ref)
}

# x position of each merge in plot.hclust (midpoint of its two children)
.node_x <- function(hc) {
  leaf_x <- match(seq_along(hc$labels), hc$order)
  n <- nrow(hc$merge)
  x <- numeric(n)
  for (i in seq_len(n)) {
    xs <- vapply(hc$merge[i, ], function(m) if (m < 0) leaf_x[-m] else x[m], numeric(1))
    x[i] <- mean(xs)
  }
  x
}